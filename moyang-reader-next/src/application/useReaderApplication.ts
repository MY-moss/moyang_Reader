import { useState } from "react";
import { useAppUpdates } from "./useAppUpdates";
import { useDocumentExport } from "./useDocumentExport";
import { useDocumentSession } from "./useDocumentSession";
import { useDocumentTabs } from "./useDocumentTabs";
import { useDocumentTransitions } from "./useDocumentTransitions";
import { useEditing } from "./useEditing";
import { useEditorHistory } from "./useEditorHistory";
import { useOpenEvents } from "./useOpenEvents";
import { useReaderCommands } from "./useReaderCommands";
import { useReaderLinks } from "./useReaderLinks";
import { useReaderState } from "./useReaderState";
import { useReadingLayout } from "./useReadingLayout";
import { useSettingsPersistence } from "./useSettingsPersistence";
import { useWorkspaceActions } from "./useWorkspaceActions";
import { useWorkspaceExport } from "./useWorkspaceExport";
import { useWorkspaceSession } from "./useWorkspaceSession";
import { useAutoSave } from "./useAutoSave";
export function useReaderApplication() {
  const [conflictPath, setConflictPath] = useState<string | null>(null);
  const readerState = useReaderState();
  const readingLayout = useReadingLayout({ ...readerState });
  const editorHistory = useEditorHistory({ ...readerState });
  const documentTransitions = useDocumentTransitions({ ...readerState, ...editorHistory, ...readingLayout });
  const appUpdates = useAppUpdates({ ...readerState });
  const workspaceSession = useWorkspaceSession({ ...readerState, ...documentTransitions });
  const documentSession = useDocumentSession({
    ...readerState,
    ...appUpdates,
    ...editorHistory,
    ...documentTransitions,
    ...workspaceSession,
  });
  const settingsPersistence = useSettingsPersistence({
    ...readerState,
    ...readingLayout,
    ...editorHistory,
    ...documentSession,
  });
  useAutoSave(readerState.documentSessions, documentSession.saveDocument);
  const workspaceActions = useWorkspaceActions({
    ...readerState,
    ...editorHistory,
    ...workspaceSession,
    ...documentSession,
    ...appUpdates,
  });
  const openEvents = useOpenEvents({ ...documentSession, ...readerState, ...workspaceSession });
  const editing = useEditing({
    ...readerState,
    ...readingLayout,
    ...workspaceSession,
    ...openEvents,
    ...documentSession,
    ...editorHistory,
    ...documentTransitions,
  });
  const documentExport = useDocumentExport({ ...readerState });
  const documentTabs = useDocumentTabs({
    ...readerState,
    ...documentTransitions,
    ...documentSession,
    ...editorHistory,
    ...appUpdates,
  });
  const readerLinks = useReaderLinks({ ...readerState, ...documentTabs });
  const readerCommands = useReaderCommands({
    ...readerState,
    ...openEvents,
    ...workspaceSession,
    ...editing,
    ...documentSession,
    ...editorHistory,
  });
  const workspaceExport = useWorkspaceExport({ ...readerState, ...documentExport, ...readerCommands });
  return {
    conflictPath,
    setConflictPath,
    sourceLocation: readerState.sourceLocation,
    setSourceLocation: readerState.setSourceLocation,
    newNoteParent: workspaceActions.newNoteParent,
    setNewNoteParent: workspaceActions.setNewNoteParent,
    createNote: workspaceActions.createNote,
    documentSessions: readerState.documentSessions,
    sessionSnapshot: readerState.sessionSnapshot,
    preferences: readerState.preferences,
    focusMode: readerState.focusMode,
    sidebarCollapsed: readerState.sidebarCollapsed,
    rightPanelOpen: readerState.rightPanelOpen,
    paneWidths: readerState.paneWidths,
    handleDrop: documentTabs.handleDrop,
    documentState: readerState.documentState,
    saveState: readerState.documentState
      ? { path: readerState.documentState.path, status: readerState.documentSessions.active()?.saveStatus ?? "idle" }
      : null,
    mode: readerState.mode,
    setMode: readerState.setMode,
    canEdit: readerCommands.canEdit,
    setExternalChangePath: readerState.setExternalChangePath,
    searchOpen: readerState.searchOpen,
    searchQuery: readerState.searchQuery,
    searchResultCount: readerState.searchResultCount,
    searchResultIndex: readerState.searchResultIndex,
    theme: readerState.theme,
    locale: readerState.locale,
    setReadingZoom: readingLayout.setReadingZoom,
    setReaderPreferences: readingLayout.setReaderPreferences,
    exportPortableSettings: settingsPersistence.exportPortableSettings,
    importPortableSettings: settingsPersistence.importPortableSettings,
    setGuideOpen: readerState.setGuideOpen,
    settingsPersistenceStatus: readerState.settingsPersistenceStatus,
    openSelectedFile: openEvents.openSelectedFile,
    handleChooseWorkspace: workspaceSession.handleChooseWorkspace,
    workspacePath: readerState.workspacePath,
    mountedWorkspaces: readerState.mountedWorkspaces,
    setQuickOpen: readerState.setQuickOpen,
    draftSnapshots: readerState.draftSnapshots,
    setDraftRecoveryOpen: readerState.setDraftRecoveryOpen,
    setSidebarCollapsed: readerState.setSidebarCollapsed,
    setFocusMode: readerState.setFocusMode,
    toggleReadingEditing: editing.toggleReadingEditing,
    toggleDocumentMode: editing.toggleDocumentMode,
    canUndo: readerCommands.canUndo,
    canRedo: readerCommands.canRedo,
    undoEditor: editorHistory.undoEditor,
    redoEditor: editorHistory.redoEditor,
    setRightPanelOpen: readerState.setRightPanelOpen,
    setCommandPaletteOpen: readerState.setCommandPaletteOpen,
    saveDocument: documentSession.saveDocument,
    handleCopy: documentExport.handleCopy,
    copyFeedback: readerState.copyFeedback,
    handleExport: documentExport.handleExport,
    handlePreviewPrint: documentExport.handlePreviewPrint,
    handleExportMarkdown: documentExport.handleExportMarkdown,
    handleExportHtml: documentExport.handleExportHtml,
    handleExportDocx: documentExport.handleExportDocx,
    setSearchOpen: readerState.setSearchOpen,
    updateStatus: readerState.updateStatus,
    availableUpdate: readerState.availableUpdate,
    setUpdateNoticeVisible: readerState.setUpdateNoticeVisible,
    checkForUpdates: appUpdates.checkForUpdates,
    setSearchQuery: readerState.setSearchQuery,
    setSearchResultIndex: readerState.setSearchResultIndex,
    moveSearchResult: readerCommands.moveSearchResult,
    cycleTheme: readerCommands.cycleTheme,
    setLocale: readerState.setLocale,
    settingsNotice: readerState.settingsNotice,
    updateNoticeVisible: readerState.updateNoticeVisible,
    updateProgress: readerState.updateProgress,
    updateError: readerState.updateError,
    installUpdate: appUpdates.installUpdate,
    relaunchUpdatedApp: appUpdates.relaunchUpdatedApp,
    dismissUpdateNotice: appUpdates.dismissUpdateNotice,
    openTabs: readerState.openTabs,
    handleSelectTab: documentTabs.handleSelectTab,
    handleCloseTab: documentTabs.handleCloseTab,
    handleCloseTabs: documentTabs.handleCloseTabs,
    handleReorderTabs: documentTabs.handleReorderTabs,
    handleExportWorkspace: workspaceExport.handleExportWorkspace,
    handleCancelWorkspaceExport: workspaceExport.handleCancelWorkspaceExport,
    workspaceExporting: readerState.workspaceExporting,
    workspaceExportProgress: readerState.workspaceExportProgress,
    workspaceExportFailures: readerState.workspaceExportFailures,
    copyWorkspaceExportFailures: workspaceExport.copyWorkspaceExportFailures,
    saveWorkspaceExportFailures: workspaceExport.saveWorkspaceExportFailures,
    workspaceExportNotice: readerState.workspaceExportNotice,
    workspaceIndexLoading: readerState.workspaceIndexLoading,
    workspaceFiles: readerState.workspaceFiles,
    workspaceFolders: readerState.workspaceFolders,
    visibleWorkspaceFiles: readerCommands.visibleWorkspaceFiles,
    visibleWorkspaceResults: readerCommands.visibleWorkspaceResults,
    workspaceExportFiles: readerCommands.workspaceExportFiles,
    recentFiles: readerState.recentFiles,
    recentWorkspaces: readerState.recentWorkspaces,
    workspaceQuery: readerState.workspaceQuery,
    workspaceSearchLoading: readerState.workspaceSearchLoading,
    availableTags: readerCommands.availableTags,
    selectedTag: readerState.selectedTag,
    selectedFileKind: readerState.selectedFileKind,
    handleOpenRecentWorkspace: workspaceSession.handleOpenRecentWorkspace,
    handleRemoveMountedWorkspace: workspaceSession.handleRemoveMountedWorkspace,
    handleCreateWorkspaceNote: workspaceActions.handleCreateWorkspaceNote,
    handleCreateWorkspaceFolder: workspaceActions.handleCreateWorkspaceFolder,
    handleRenameWorkspaceEntry: workspaceActions.handleRenameWorkspaceEntry,
    handleDeleteWorkspaceEntry: workspaceActions.handleDeleteWorkspaceEntry,
    handleDuplicateWorkspaceEntry: workspaceActions.handleDuplicateWorkspaceEntry,
    handleShowWorkspaceDetails: workspaceActions.handleShowWorkspaceDetails,
    handleRevealWorkspaceEntry: workspaceActions.handleRevealWorkspaceEntry,
    handleCopyWorkspacePath: workspaceActions.handleCopyWorkspacePath,
    handleCopyWorkspaceRelativePath: workspaceActions.handleCopyWorkspaceRelativePath,
    handleCopyWorkspaceName: workspaceActions.handleCopyWorkspaceName,
    handleRefreshWorkspaceEntry: workspaceActions.handleRefreshWorkspaceEntry,
    setWorkspaceQuery: readerState.setWorkspaceQuery,
    setSelectedTag: readerState.setSelectedTag,
    setSelectedFileKind: readerState.setSelectedFileKind,
    workspaceLoading: readerState.workspaceLoading,
    workspaceWatchError: readerState.workspaceWatchError,
    resizePane: readingLayout.resizePane,
    resetPane: readingLayout.resetPane,
    contentAreaRef: readerState.contentAreaRef,
    handleReaderWheel: readingLayout.handleReaderWheel,
    readingZoomNotice: readerState.readingZoomNotice,
    loading: readerState.loading,
    externalChangePath: readerState.externalChangePath,
    reloadExternalChange: documentSession.reloadExternalChange,
    overwriteExternalChange: openEvents.overwriteExternalChange,
    draftRecovery: readerState.draftRecovery,
    recoverDraft: editing.recoverDraft,
    deferDraftRecovery: editing.deferDraftRecovery,
    discardDraft: editing.discardDraft,
    error: readerState.error,
    articleRef: readerState.articleRef,
    handleReaderClick: readerLinks.handleReaderClick,
    handleReaderContextMenu: readerLinks.handleReaderContextMenu,
    sourceDraft: readerState.sourceDraft,
    updateSource: editing.updateSource,
    handleInsertLink: editing.handleInsertLink,
    handleFindEditorText: editing.handleFindEditorText,
    setSettingsNotice: readerState.setSettingsNotice,
    wikiLinkCandidates: readerCommands.wikiLinkCandidates,
    handleSourcePaste: editing.handleSourcePaste,
    readerContextMenu: readerState.readerContextMenu,
    handleCopyReaderText: readerLinks.handleCopyReaderText,
    handleCopyReaderLink: readerLinks.handleCopyReaderLink,
    handleOpenReaderLink: readerLinks.handleOpenReaderLink,
    handleCopyReaderDocumentPath: readerLinks.handleCopyReaderDocumentPath,
    setReaderContextMenu: readerState.setReaderContextMenu,
    currentIndexEntry: readerCommands.currentIndexEntry,
    backlinks: readerCommands.backlinks,
    outgoing: readerCommands.outgoing,
    currentHeadingId: readerState.currentHeadingId,
    currentHeading: readerState.currentHeading,
    readingProgress: readerState.readingProgress,
    activeContextTab: readerState.activeContextTab,
    setActiveContextTab: readerState.setActiveContextTab,
    handleCreateNote: workspaceActions.handleCreateNote,
    setGraphOpen: readerState.setGraphOpen,
    scrollToReaderEdge: readingLayout.scrollToReaderEdge,
    navigateToHeading: readingLayout.navigateToHeading,
    currentVersion: readerState.currentVersion,
    inputRef: readerState.inputRef,
    handleBrowserFiles: documentTabs.handleBrowserFiles,
    graphOpen: readerState.graphOpen,
    workspaceIndex: readerState.workspaceIndex,
    workspaceEntryDetails: readerState.workspaceEntryDetails,
    setWorkspaceEntryDetails: readerState.setWorkspaceEntryDetails,
    printPreview: readerState.printPreview,
    handlePrintPreview: documentExport.handlePrintPreview,
    handleClosePrintPreview: documentExport.handleClosePrintPreview,
    quickOpen: readerState.quickOpen,
    quickOpenItems: readerCommands.quickOpenItems,
    commandPaletteOpen: readerState.commandPaletteOpen,
    commandItems: readerCommands.commandItems,
    executeCommand: readerCommands.executeCommand,
    draftRecoveryOpen: readerState.draftRecoveryOpen,
    openDraftSnapshot: editing.openDraftSnapshot,
    requestDraftDiscardByPath: editing.requestDraftDiscardByPath,
    clearAllDrafts: editing.clearAllDrafts,
    draftDiscardRequest: readerState.draftDiscardRequest,
    cancelDraftDiscard: editing.cancelDraftDiscard,
    confirmDraftDiscard: editing.confirmDraftDiscard,
    closeConfirmationOpen: readerState.closeConfirmationOpen,
    cancelCloseConfirmation: documentTransitions.cancelCloseConfirmation,
    confirmClose: documentTransitions.confirmClose,
    externalOverwriteConfirmationOpen: readerState.externalOverwriteConfirmationOpen,
    cancelExternalOverwrite: openEvents.cancelExternalOverwrite,
    confirmExternalOverwrite: openEvents.confirmExternalOverwrite,
    guideOpen: readerState.guideOpen,
    closeGettingStarted: openEvents.closeGettingStarted,
    openDocumentFromGuide: openEvents.openDocumentFromGuide,
    addWorkspaceFromGuide: openEvents.addWorkspaceFromGuide,
  };
}
export type ReaderApplication = ReturnType<typeof useReaderApplication>;
